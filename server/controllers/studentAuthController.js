import Student from "../models/Student.js";
import { startSession } from "../services/sessionService.js";
import { isLocked, recordFailure, clearFailures } from "../services/loginGuard.js";
import { env } from "../config/env.js";
import { AppError, asyncHandler } from "../utils/AppError.js";
import { burnPasswordCheck } from "../utils/dummyHash.js";

export const registerStudent = asyncHandler(async (req, res) => {
  const { studentId, name, password } = req.body;

  // studentId is intentionally case-sensitive
  if (await Student.exists({ studentId })) {
    throw new AppError(400, "Student ID already exists");
  }

  // Password is hashed by the model's pre-save hook; the anonymous alias is generated by
  // the model. In the (very unlikely) event of an alias collision, draw a new one.
  let student;
  for (let attempt = 0; attempt < 5 && !student; attempt++) {
    try {
      student = await Student.create({ studentId, name, password });
    } catch (err) {
      if (err.code === 11000 && err.keyPattern?.alias) continue;
      throw err;
    }
  }
  if (!student) throw new AppError(503, "Could not create account. Please try again.");
  const session = await startSession(res, "student", student);
  res.status(201).json({ message: "Signup successful", ...session });
});

export const loginStudent = asyncHandler(async (req, res) => {
  const { studentId, password } = req.body;

  if (await isLocked("student", studentId, req.ip)) {
    throw new AppError(429, "Too many failed attempts. Try again in 15 minutes.");
  }

  const student = await Student.findOne({ studentId });
  const ok = student
    ? await student.matchPassword(password)
    : await burnPasswordCheck(password);

  if (!student || !ok) {
    await recordFailure("student", studentId, req.ip);
    throw new AppError(401, "Invalid ID or password");
  }

  await clearFailures("student", studentId, req.ip);
  const session = await startSession(res, "student", student);
  res.status(200).json({ message: "Login successful", ...session });
});
